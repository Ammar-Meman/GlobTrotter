export const findCityInLookup = (name) => {
  if (!name) return null;
  const lower = name.trim().toLowerCase();
  return (
    CITIES_DATA.find(
      (c) =>
        c.cityName.toLowerCase() === lower ||
        c.cityName.toLowerCase().includes(lower) ||
        lower.includes(c.cityName.toLowerCase())
    ) || null
  );
};
